"""
Simulator for my ACMSE paper: burn-rate alerts vs a fixed threshold line.

I am comparing three paging rules on the same traffic, minute by minute:

  * fixed line (static) -- page when the error rate of the last 5 minutes
    goes above 2% and stays there for 5 minutes
  * burn rate (multi-window) -- Google's SRE Workbook rules: page at 14.4x
    burn over 1 hour (with the 5-minute window also at 14.4x), or 6x burn
    over 6 hours (with the 30-minute window also at 6x)
  * scaled line -- same like the fixed line, but the line moves with the
    SLO (6x of the allowed error rate). I added this third rule so the
    comparison stays fair: it separates "the line moves with the SLO"
    from "there are two windows".

The traffic is real (from a public trace). The failures are generated by
this program only: even a healthy service keeps getting small errors, so
every minute has some background failures (probability = one quarter of
the allowed error budget), and an incident adds more failures on top.

Author: Manjari Mettu
How I checked this code: validate_simulator.py runs the cases I worked
out by hand first. Only after all those matched, this code is used for
the real runs.
"""

import numpy as np

MINUTES = 720  # 720 minutes = one full 12 hours, one row per minute

# The three incident types I test.
# Each entry: (extra error probability per minute, duration in minutes).
# "partial" means only 20% of the traffic gets 5% errors, so overall it
# comes to 1% errors -- like one part of the service is degraded.
INCIDENTS = {
    "spike":   (0.25, 10),
    "leak":    (0.01, 240),
    "partial": (0.01, 120),
}

SLOS = [0.990, 0.995, 0.999]


def window_rate(failures, calls, t, width):
    """Error rate of the last `width` minutes, up to minute t.

    I count it with call volumes (total failures / total calls in the
    window), same like real monitoring tools do -- a busy minute counts
    more than a quiet minute. If the window is not full yet, it returns
    None, because a rule should not fire on half data.
    """
    if t < width - 1:
        return None
    f = failures[t - width + 1: t + 1].sum()
    c = calls[t - width + 1: t + 1].sum()
    if c == 0:
        return None
    return f / c


def page_worthy(shape, slo):
    """Did this incident deserve a page? I fixed this definition before
    running anything (paper Section 3.3): yes, if nobody attending it
    means it burns the error budget at 6x speed or more, or if it is a
    sudden spike."""
    if shape == "spike":
        return True
    added_rate, _ = INCIDENTS[shape]
    return added_rate / (1.0 - slo) >= 6.0


class Strategy:
    """One paging rule, along with its state.

    The logic is the same for every rule: when the rule's condition holds
    for long enough, it pages -- once. After paging, it stays quiet until
    things calm down: the 5-minute error rate has to stay below the rule's
    own clear line for 10 minutes together. Only then it can page again.
    For the burn-rate rule, sustain is 1 minute, because its short window
    is already the confirmation.
    """

    def __init__(self, name, condition, clear_level, sustain):
        self.name = name
        self.condition = condition      # function: (failures, calls, minute, slo) -> True/False
        self.clear_level = clear_level  # function: (slo) -> rate below which the incident is treated as over
        self.sustain = sustain          # how many minutes together the condition must hold before paging

    def run(self, failures, calls, slo):
        pages = []
        paged = False
        hold = 0   # how many minutes together the condition is holding
        clear = 0  # how many minutes together things are calm (after a page)
        for t in range(len(calls)):
            if not paged:
                if self.condition(failures, calls, t, slo):
                    hold += 1
                    if hold >= self.sustain:
                        pages.append(t)
                        paged = True
                        hold = 0
                        clear = 0
                else:
                    hold = 0
            else:
                rate5 = window_rate(failures, calls, t, 5)
                if rate5 is not None and rate5 < self.clear_level(slo):
                    clear += 1
                    if clear >= 10:
                        paged = False
                        clear = 0
                else:
                    clear = 0
        return pages


def _static_condition(line):
    def condition(failures, calls, t, slo):
        rate = window_rate(failures, calls, t, 5)
        return rate is not None and rate > line(slo)
    return condition


def _burn_condition(failures, calls, t, slo):
    budget = 1.0 - slo
    eps = 1e-9  # small tolerance: if the burn touches the line exactly, it should count as fired
    r5 = window_rate(failures, calls, t, 5)
    r30 = window_rate(failures, calls, t, 30)
    r60 = window_rate(failures, calls, t, 60)
    r360 = window_rate(failures, calls, t, 360)
    fast = (r60 is not None and r5 is not None
            and r60 / budget >= 14.4 - eps and r5 / budget >= 14.4 - eps)
    slow = (r360 is not None and r30 is not None
            and r360 / budget >= 6.0 - eps and r30 / budget >= 6.0 - eps)
    return fast or slow


def make_strategies():
    return [
        Strategy("static", _static_condition(lambda slo: 0.02),
                 clear_level=lambda slo: 0.02, sustain=5),
        Strategy("burn", _burn_condition,
                 clear_level=lambda slo: 1.0 * (1.0 - slo), sustain=1),
        Strategy("scaled", _static_condition(lambda slo: 6.0 * (1.0 - slo)),
                 clear_level=lambda slo: 6.0 * (1.0 - slo), sustain=5),
    ]


def generate_failures(calls, slo, shape=None, onset=None, seed=0):
    """Make one run's failures, minute by minute.

    For every minute, failures are drawn from a binomial distribution
    with that minute's call count as n. In healthy time the probability
    is the background one (1/4 of the error budget). If an incident is
    running, its error probability is added on top for its duration,
    starting at `onset`.
    """
    rng = np.random.default_rng(seed)
    p = np.full(len(calls), 0.25 * (1.0 - slo))
    if shape is not None:
        added, duration = INCIDENTS[shape]
        end = min(onset + duration, len(calls))
        p[onset:end] += added
    p = np.clip(p, 0.0, 0.999)
    return rng.binomial(calls, p)


def run_scenario(calls, slo, shape, onset, seed):
    """Run one full test (one random seed) with all three rules.

    Collects the numbers I report in the paper: paged or missed, time to
    detect, how many requests failed before the page, and how much of
    the 30-day error budget was spent before the page. If shape is None,
    it is a control run with no incident -- in that run every page is a
    false page.
    """
    calls = np.asarray(calls, dtype=int)
    failures = generate_failures(calls, slo, shape, onset, seed)
    mean_calls = calls.mean()
    budget_30d_failures = 30 * MINUTES * 2 * mean_calls * (1.0 - slo)  # allowed failures in 30 days (30 x 1440 minutes) at the average call rate
    out = {}
    for strat in make_strategies():
        pages = strat.run(failures, calls, slo)
        metrics = {"pages": pages, "n_pages": len(pages)}
        if shape is not None:
            _, duration = INCIDENTS[shape]
            inc_end = min(onset + duration, len(calls)) - 1
            worthy = page_worthy(shape, slo)
            hit = pages[0] if pages and pages[0] <= inc_end else None
            metrics["page_worthy"] = worthy
            metrics["paged"] = hit is not None
            metrics["missed"] = worthy and hit is None
            metrics["false_page"] = (not worthy) and hit is not None
            if hit is not None:
                metrics["ttd"] = hit - onset
                harm_end = hit
            else:
                metrics["ttd"] = None
                harm_end = inc_end
            harm = int(failures[onset:harm_end + 1].sum())
            metrics["harm_failed"] = harm
            metrics["harm_budget_pct"] = 100.0 * harm / budget_30d_failures
        out[strat.name] = metrics
    return out
